export const CURATED_KANJI = [];
const seenKanji = new Set();

for (const row of RAW_KANJI_ROWS) {
  const [character, hanViet, jlpt, strokes, radical, onyomiCsv, kunyomiCsv, viCsv, enCsv, examplesCsv] = row;
  if (seenKanji.has(character)) continue;
  seenKanji.add(character);
  CURATED_KANJI.push({
    character,
    hanViet,
    jlpt,
    strokes,
    radical,
    onyomi: onyomiCsv ? onyomiCsv.split(',').map(s => s.trim()).filter(Boolean) : [],
    kunyomi: kunyomiCsv ? kunyomiCsv.split(',').map(s => s.trim()).filter(Boolean) : [],
    meanings: {
      vi: viCsv.split(',').map(s => s.trim()).filter(Boolean),
      en: enCsv.split(',').map(s => s.trim()).filter(Boolean)
    },
    examples: examplesCsv.split(',').map(s => s.trim()).filter(Boolean)
  });
}

export const HAN_VIET_MAP = { ...EXTRA_HAN_VIET_MAP };
for (const k of CURATED_KANJI) {
  HAN_VIET_MAP[k.character] = k.hanViet;
}

export function computeHanViet(word) {
  if (!word || typeof word !== 'string') return '';
  const parts = [];
  for (const ch of word) {
    if (HAN_VIET_MAP[ch]) {
      parts.push(HAN_VIET_MAP[ch]);
    }
  }
  return parts.join(' ');
}
